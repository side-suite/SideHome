private val pathCache = HashMap<String, Path>()
private fun parsed(d: String): Path =
    pathCache.getOrPut(d) { PathParser().parsePathString(d).toPath() }

private fun DrawScope.drawGlyph(name: String, color: Color, strokeWidthUnits: Float) {
    val prims = GLYPHS[name] ?: GLYPHS["app"]!!
    val s = size.minDimension / 24f
    val stroke = Stroke(width = strokeWidthUnits, cap = StrokeCap.Round, join = StrokeJoin.Round)
    scale(s, s, pivot = Offset.Zero) {
        for (p in prims) when (p) {
            is P -> drawPath(parsed(p.d), color = color, style = stroke)
            is C -> drawCircle(color = color, radius = p.r, center = Offset(p.cx, p.cy), style = stroke)
            is R -> drawRoundRect(
                color = color,
                topLeft = Offset(p.x, p.y),
                size = Size(p.w, p.h),
                cornerRadius = CornerRadius(p.rx, p.rx),
                style = stroke,
            )
        }
    }
}

// Glyphs are rasterised to a bitmap once per (glyph, colour, size, stroke) and cached,
// so scrolling a list of icons blits cached textures instead of re-stroking vector paths
// every frame — the difference between a smooth and a janky drawer on the A22.
private val glyphCache = HashMap<String, ImageBitmap>()

private fun glyphBitmap(glyph: String, argb: Int, px: Int, strokeWidthUnits: Float): ImageBitmap {
    val key = "$glyph|$argb|$px|$strokeWidthUnits"
    return glyphCache.getOrPut(key) {
        val bmp = ImageBitmap(px, px)
        val canvas = Canvas(bmp)
        CanvasDrawScope().draw(Density(1f), LayoutDirection.Ltr, canvas, Size(px.toFloat(), px.toFloat())) {
            drawGlyph(glyph, Color(argb), strokeWidthUnits)
        }
        bmp
    }
}

/**
 * A thin line icon at [size], stroked in [color] — drawn from a cached bitmap.
 *
 * [badge] paints a small filled notification dot at the glyph's top-right (SID-46); null — the
 * default — leaves the icon bare, so every call site that doesn't care about notifications reads
 * exactly as before. The dot is a **Compose overlay, not part of the bitmap**, for two reasons:
 * [glyphBitmap]'s cache is keyed on `(glyph, colour, size, stroke)`, so baking the dot in would mean
 * a second cache entry per glyph *and* a re-raster every time a notification arrived or cleared —
 * paying vector-stroking cost on the A22 for a mark that is one filled circle; and as a sibling the
 * dot can fade in and drift with the accent independently of the line art it sits on.
 */
@Composable
fun LineIcon(
    glyph: String,
    color: Color,
    size: Dp,
    strokeWidthUnits: Float = 1.55f,
    modifier: Modifier = Modifier,
    badge: Color? = null,
) {
    val px = with(LocalDensity.current) { size.roundToPx() }.coerceAtLeast(1)
    val argb = color.toArgb()
    val bmp = remember(glyph, argb, px, strokeWidthUnits) { glyphBitmap(glyph, argb, px, strokeWidthUnits) }
    if (badge == null) {
        // The overwhelmingly common case stays exactly one Image — no Box wrapper in the layout pass.
        Image(bitmap = bmp, contentDescription = null, modifier = modifier.size(size))
    } else {
        Box(modifier = modifier.size(size)) {
            Image(bitmap = bmp, contentDescription = null, modifier = Modifier.size(size))
            // Sized off the stroke, in the glyph's own 24-unit space, so the dot keeps its weight
            // relative to the line art at every icon size. See BadgeMetrics for the tuning knobs.
            val diameter = (size / 24f) * (strokeWidthUnits * BadgeMetrics.DiameterStrokes)
            Box(
                modifier = Modifier
                    .align(Alignment.TopEnd)
                    .offset(x = diameter * BadgeMetrics.Overhang, y = -diameter * BadgeMetrics.Overhang)
                    .size(diameter)
                    .background(badge, CircleShape),
            )
        }
    }
}
